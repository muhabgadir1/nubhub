/**
 * Builds the guess dictionaries into src/wordle/dict-<n>.js, one per length.
 *
 * The system dictionary (Webster's 2nd, at /usr/share/dict/words) is a lemma
 * list: it has "cake" but not "cakes", "box" but not "boxes". Rejecting those
 * is the one failure a word game cannot afford, so the plurals and past tenses
 * are derived here from the shorter entries. Over-accepting an obscure word is
 * a shrug; rejecting a common one ends the game.
 *
 * Run with `npm run words`. The output is committed, so the app never reads
 * from the system at runtime.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { ANSWERS, LENGTHS } from "../src/wordle/answers.js";
import { EXTRA_GUESSES } from "../src/wordle/extras.js";

const SYSTEM_DICT = "/usr/share/dict/words";

// Bucket the system dictionary by length once, rather than re-scanning per word
// length. Lengths 3 and 4 are kept only as raw material for the derivations.
const byLength = new Map();
for (const line of readFileSync(SYSTEM_DICT, "utf8").split("\n")) {
  const w = line.trim().toLowerCase();
  if (!/^[a-z]+$/.test(w)) continue;
  if (!byLength.has(w.length)) byLength.set(w.length, []);
  byLength.get(w.length).push(w);
}
const at = (n) => byLength.get(n) ?? [];

/**
 * Every form of one base word.
 *
 * Webster's is a lemma list with *inconsistent* inflections — it happens to
 * carry "running" and "quickly", but it has "embezzle" and "embezzler" and no
 * "embezzling", and it has no y-to-ies plurals at all. Deriving every form from
 * every base rather than trusting what is listed is what stops a player being
 * told a word they know perfectly well is not a word.
 *
 * This over-generates: "catness" and "runly" come out of it too. That is the
 * right way round to be wrong. Accepting a non-word costs a player one row of a
 * guess they typed by mistake; rejecting a real one ends the game in an
 * argument with the dictionary.
 */
function* forms(w) {
  yield w;

  const vowelY = /[^aeiou]y$/.test(w);   // city, happy — the y turns into i
  const sibilant = /([sxz]|ch|sh)$/.test(w);
  const silentE = w.endsWith("e");
  // run → running, big → bigger: a short word ending consonant-vowel-consonant
  // doubles that last consonant. w, x and y never double.
  const doubles = /[^aeiou][aeiou][^aeiouwxy]$/.test(w) && w.length <= 5;
  const stem = w.slice(0, -1);

  // plural and third person
  if (sibilant) yield w + "es";
  else if (vowelY) yield stem + "ies";
  else yield w + "s";

  // past, agent, superlative, participle
  if (silentE) {
    yield w + "d";
    yield w + "r";
    yield w + "st";
    yield stem + "ing";
  } else if (vowelY) {
    yield stem + "ied";
    yield stem + "ier";
    yield stem + "iest";
    yield w + "ing";
  } else {
    yield w + "ed";
    yield w + "er";
    yield w + "est";
    yield w + "ing";
    if (doubles) {
      const d = w + w[w.length - 1];
      yield d + "ed";
      yield d + "er";
      yield d + "est";
      yield d + "ing";
    }
    // panic → panicking, mimic → mimicking. A bare "panicing" would be read
    // with a soft c, so English wedges a k in.
    if (w.endsWith("c")) {
      yield w + "ked";
      yield w + "king";
      yield w + "ker";
    }
  }

  // adverbs and abstract nouns
  if (vowelY) {
    yield stem + "ily";
    yield stem + "iness";
  } else {
    yield w + "ly";
    yield w + "ness";
  }
}

/**
 * Every word of length `n` a guess is allowed to be.
 *
 * Built by running every base word in the dictionary through `forms()` once and
 * keeping whatever lands at the right length, rather than by asking each length
 * which shorter words could reach it.
 */
function buildAll() {
  const buckets = new Map();
  const keep = (w) => {
    if (!/^[a-z]+$/.test(w)) return;
    const n = w.length;
    if (n < MIN || n > MAX) return;
    if (!buckets.has(n)) buckets.set(n, new Set());
    buckets.get(n).add(w);
  };

  for (const list of byLength.values()) {
    for (const base of list) for (const form of forms(base)) keep(form);
  }

  // Everything a player is expected to guess must be guessable.
  for (const n of LENGTHS) for (const w of ANSWERS[n] ?? []) keep(w);
  for (const w of EXTRA_GUESSES) keep(w);

  return buckets;
}

const MIN = Math.min(...LENGTHS);
const MAX = Math.max(...LENGTHS);
const buckets = buildAll();

const summary = [];
for (const n of LENGTHS) {
  const sorted = [...(buckets.get(n) ?? [])].sort();
  // One packed string rather than an array of quoted strings: a third of the
  // bytes, and it splits back into a Set in a single pass.
  writeFileSync(
    new URL(`../src/wordle/dict-${n}.js`, import.meta.url),
    `/**
 * Every ${n}-letter word a guess is allowed to be — ${sorted.length} of them.
 *
 * GENERATED by scripts/build-words.mjs. Do not edit by hand; edit answers.js
 * or extras.js and re-run \`npm run words\`.
 */
export const PACKED =
  "${sorted.join("")}";
`,
  );
  summary.push({ n, count: sorted.length, kb: Math.round(sorted.length * n / 1024) });
}

for (const { n, count, kb } of summary) {
  console.log(`dict-${n}.js — ${String(count).padStart(6)} words, ${String(kb).padStart(4)}KB packed`);
}
